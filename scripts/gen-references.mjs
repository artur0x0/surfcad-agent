#!/usr/bin/env node
/**
 * Write the generated skill references from the vendored catalogs.
 * Hand-written references (modeling-workflow.md, failure-modes.md, examples.md)
 * are left alone. Exits non-zero if a catalog helper has no group.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const catalogDir = join(repoRoot, 'packages/surfcad/vendor/src/lib/surfcad/catalog');
const refDir = join(repoRoot, 'plugins/surfcad/skills/surfcad/references');

const GENERATED = 'Generated by `scripts/gen-references.mjs` from the vendored catalogs. Do not edit by hand.';

/** Catalog helper name → section title. Every helpers.json name must appear once. */
const GROUPS = [
  ['Shell, stock, and patterns', [
    'shell', 'hollow', 'getScaleRatio', 'roundedBox', 'tube', 'rectTube', 'hexPrism',
    'mirror', 'array3D', 'polarArray', 'center', 'align', 'getDimensions',
  ]],
  ['Draft, faces, booleans, and moves', [
    'addDraft', 'draftFaces', 'cut', 'booleanBodies', 'externalBody', 'move',
    'moveFace', 'deleteFace',
  ]],
  ['Loft and sweep', [
    'loft', 'sumSqDist', 'rotateContour', 'sweep', 'sweepPoints',
  ]],
  ['Vector helpers', [
    'vecAdd', 'vecSub', 'vecMul', 'vecDot', 'vecCross', 'vecNorm', 'vecNormalize',
  ]],
  ['Selection and placement', [
    'facesByNormal', 'planarFaceAt', 'edgesByOrientation', 'workplaneFromFace',
    'placeInFrame', 'transformByFrame', 'placeOnFace',
  ]],
  ['Holes, chamfers, and fasteners', [
    'hole', 'holeSpan', 'cboreHole', 'cskHole', 'chamferEdges', 'convexEdges',
    'concaveEdges', 'signedFeatureEdges', 'holePattern', 'clearanceHole', 'tapDrillHole',
    'fastenerClearanceDia', 'fastenerTapDrillDia', 'fastenerMajorDia',
    'listFastenerSizes', 'resolveFastenerSize',
  ]],
  ['Fillets', [
    'filletEdges', 'filletAlongPath',
  ]],
  ['Profiles, extrude, revolve, and loft', [
    'profileCircle', 'profileRectangle', 'profilePolygon', 'makeCrossSection',
    'makeExtrude', 'makeRevolve', 'makeLoft', 'offsetPlaneFrame',
  ]],
  ['Edge identity and sweep paths', [
    'edge', 'edgesBetween', 'boundaryEdges', 'makeSweepPath',
  ]],
  ['Sheet metal', [
    'sheetMetalSolid',
  ]],
];

function readJson(name) {
  return JSON.parse(readFileSync(join(catalogDir, name), 'utf8'));
}

function fence(lang, body) {
  const text = String(body ?? '').replace(/\s+$/, '');
  return `\`\`\`${lang}\n${text}\n\`\`\``;
}

function helpersMarkdown(catalog) {
  const helpers = catalog.helpers;
  if (!Array.isArray(helpers)) throw new Error('helpers.json has no helpers array');
  const byName = new Map(helpers.map((helper) => [helper.name, helper]));
  const placed = new Set();
  const lines = [
    '# SurfCAD helpers',
    '',
    GENERATED,
    '',
    `Source: \`${catalog.generatedFrom}\`. Count: ${catalog.count}.`,
    '',
    'Units are millimetres. A script `return`s a Manifold. These names are injected as function parameters, so a top-level `let` or `const` with the same name does not compile. See [failure modes](failure-modes.md).',
    '',
  ];
  for (const [title, names] of GROUPS) {
    lines.push(`## ${title}`, '');
    for (const name of names) {
      const helper = byName.get(name);
      if (!helper) throw new Error(`group lists ${name}, which is not in helpers.json`);
      if (placed.has(name)) throw new Error(`duplicate group entry ${name}`);
      placed.add(name);
      lines.push(`### ${name}`, '');
      lines.push(`\`${helper.signature}\``, '');
      if (Array.isArray(helper.params) && helper.params.length) {
        lines.push('| Param | Text | Default |', '| --- | --- | --- |');
        for (const param of helper.params) {
          const def = param.default == null ? '' : `\`${String(param.default).replace(/\|/g, '\\|')}\``;
          const text = String(param.text ?? param.name).replace(/\|/g, '\\|');
          lines.push(`| \`${param.name}\` | \`${text}\` | ${def} |`);
        }
        lines.push('');
      }
      if (helper.description) {
        lines.push(String(helper.description).trim(), '');
      }
      const examples = (helper.examples || []).map((example) => String(example).trim()).filter(Boolean);
      if (examples.length) {
        lines.push('Example:', '');
        for (const example of examples) lines.push(fence('javascript', example), '');
      }
      if (helper.doc && String(helper.doc).trim() && String(helper.doc).trim() !== String(helper.description || '').trim()) {
        lines.push(String(helper.doc).trim(), '');
      }
    }
  }
  const missing = helpers.filter((helper) => !placed.has(helper.name)).map((helper) => helper.name);
  if (missing.length) {
    throw new Error(`helpers with no group: ${missing.join(', ')}`);
  }
  if (placed.size !== helpers.length) {
    throw new Error(`grouped ${placed.size} helpers, catalog has ${helpers.length}`);
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

function memberSection(title, members) {
  const lines = [`## ${title}`, ''];
  for (const member of members) {
    lines.push(`### ${member.kind} ${member.name}`, '');
    lines.push(`\`${member.signature}\``, '');
    if (member.description) lines.push(String(member.description).trim(), '');
    if (member.doc && String(member.doc).trim() && String(member.doc).trim() !== String(member.description || '').trim()) {
      lines.push(String(member.doc).trim(), '');
    }
  }
  return lines;
}

function manifoldMarkdown(catalog) {
  const lines = [
    '# Manifold API',
    '',
    GENERATED,
    '',
    `Kernel: \`${catalog.kernel}\`. Types: \`${catalog.types}\`.`,
    '',
    catalog.note || '',
    '',
    'Use SurfCAD helpers for fillets, shells, holes, lofts, and sheet metal. Use `Manifold` and `CrossSection` for stock solids and booleans. `status()` on this build is an enum object, not the string `"NoError"` from npm `manifold-3d`. `runScript` reports `status: "NoError"` only when the solid is valid.',
    '',
    ...memberSection('Module functions', catalog.functions || []),
    ...memberSection('Manifold', catalog.Manifold || []),
    ...memberSection('CrossSection', catalog.CrossSection || []),
    ...memberSection('Mesh', catalog.Mesh || []),
  ];
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
}

function assemblyMarkdown(schema) {
  const part = schema.properties.parts.items;
  const fields = part.properties;
  const lines = [
    '# Assembly format (`.surf.json`)',
    '',
    GENERATED,
    '',
    schema.description || '',
    '',
    `- Document \`$id\`: \`${schema.$id}\`.`,
    `- \`format\` is exactly \`${schema.properties.format.const}\`.`,
    `- \`version\` is exactly \`${schema.properties.version.const}\`.`,
    `- Required document fields: ${schema.required.map((name) => `\`${name}\``).join(', ')}.`,
    `- \`name\` is the path-safe assembly folder name.`,
    `- \`activeId\` is the repo path of the active part, or null.`,
    `- Each part requires ${part.required.map((name) => `\`${name}\``).join(', ')}.`,
    `- \`parts[].id\` pattern: \`${fields.id.pattern}\`. ${fields.id.description}`,
    `- \`parts[].path\`: ${fields.path.description}`,
    `- \`parts[].position\`: ${fields.position.description}`,
    `- \`parts[].sheetMetal\` requires \`sku\`. ${fields.sheetMetal.description}`,
    `- \`parts[].copiedFrom\`: ${fields.copiedFrom.description}`,
    `- Surf id examples: ${schema.defs.surfId.examples.map((id) => `\`${id}\``).join(', ')}.`,
    `- The part script's first line matches \`${schema.defs.surfIdHeader.pattern}\`. ${schema.defs.surfIdHeader.description}`,
    '- A part that has not been pushed uses the `local-` prefix on that id. The same prefix is optional on `copiedFrom`.',
    '- Part rows reference scripts by repo path (`{ id, path }`). They do not inline the script.',
    '',
    'Schema:',
    '',
    fence('json', JSON.stringify(schema, null, 2)),
    '',
  ];
  return `${lines.join('\n')}\n`;
}

function sheetMarkdown(catalog) {
  const lines = [
    '# Sheet metal',
    '',
    GENERATED,
    '',
    '## Part binding',
    '',
    catalog.partSheetMetal.description,
    '',
    `Source: \`${catalog.partSheetMetal.source}\`.`,
    '',
  ];
  for (const [name, field] of Object.entries(catalog.partSheetMetal.fields)) {
    const required = field.required ? ' required' : '';
    lines.push(`- \`${name}\` (${field.type}${required})${field.description ? `: ${field.description}` : ''}`);
  }
  lines.push(
    '',
    '## Script block',
    '',
    `Begin marker: \`${catalog.script.begin}\``,
    '',
    `End marker: \`${catalog.script.end}\``,
    '',
    `Spec line: \`${catalog.script.specLine}\``,
    '',
    `Solid line: \`${catalog.script.solid}\``,
    '',
    catalog.script.note,
    '',
    `Source: \`${catalog.script.source}\`.`,
    '',
    '## Spec',
    '',
    `Source: \`${catalog.spec.source}\`.`,
    '',
    fence('javascript', catalog.spec.comment),
    '',
  );
  for (const [name, text] of Object.entries(catalog.spec.fields)) {
    lines.push(`- \`${name}\`: ${text}`);
  }
  lines.push(
    '',
    '## DFM',
    '',
    `Entry: \`${catalog.dfm.entry}\`.`,
    '',
    catalog.dfm.note,
    '',
    `Source: \`${catalog.dfm.source}\`.`,
    '',
    '| Rule | Level | Check |',
    '| --- | --- | --- |',
  );
  for (const rule of catalog.dfm.rules) {
    lines.push(`| \`${rule.rule}\` | ${rule.level} | ${rule.check} |`);
  }
  lines.push(
    '',
    '## Export',
    '',
    `Entry: \`${catalog.export.entry}\`.`,
    '',
    catalog.export.step,
    '',
    catalog.export.dxf,
    '',
    catalog.export.headless,
    '',
    `Source: \`${catalog.export.source}\`.`,
    '',
  );
  return `${lines.join('\n')}\n`;
}

const outputs = {
  'helpers.md': helpersMarkdown(readJson('helpers.json')),
  'manifold-api.md': manifoldMarkdown(readJson('manifold.json')),
  'assembly-format.md': assemblyMarkdown(readJson('assembly.schema.json')),
  'sheet-metal.md': sheetMarkdown(readJson('sheet-metal.json')),
};

for (const [name, body] of Object.entries(outputs)) {
  writeFileSync(join(refDir, name), body);
  console.log(`gen-references: wrote references/${name} (${body.length} bytes)`);
}
